package com.example.jibnam;

/** WaterCalculate : คำนวณน้ำ — เป้าที่ควรดื่ม, ดื่มแล้ว/ยังขาด, ระดับการดื่ม, ผลจากออกกำลังกาย, สรุปผล */
public class WaterCalculate {

    /*
     * น้ำที่ควรดื่มต่อวัน (ลิตร) = น้ำหนัก(กก.) × 33 มล.
     * มาจากสูตรที่ใช้กันในไทย น้ำหนัก × 2.2 × 30 ÷ 2 (มล.) ซึ่งเท่ากับ น้ำหนัก × 33 มล.
     * เทียบค่าแนะนำ: กรมอนามัย ~2 ลิตร/วัน, EFSA น้ำรวม 2.0 L (หญิง) / 2.5 L (ชาย) รวมน้ำจากอาหาร
     * เช่น 60 กก. → 1.98 L
     */
    public static double targetL(double weightKg) {
        return Math.round(weightKg * 33) / 1000.0;
    }
}
